# frontend/app.py - Main Navigation & Auth Guard
import streamlit as st
import requests
from datetime import datetime
from theme import apply_theme, hero, feature_card

st.set_page_config(
    page_title="Student Feedback Analyzer",
    page_icon="🤖",
    layout="wide",
    initial_sidebar_state="expanded"
)

# Global API URL
API_URL = "http://localhost:8000/api/v1"

# Auth Guard: Redirect to login if not authenticated
def check_authentication():
    if "user_id" not in st.session_state or not st.session_state.user_id:
        st.switch_page("pages/0_Login.py")

check_authentication()

# Soft-lavender global theme (styles the card-style sidebar nav too)
apply_theme()

# Sidebar: user badge + logout (navigation cards are the styled native nav)
with st.sidebar:
    col1, col2 = st.columns([3, 1])
    with col1:
        st.markdown(f"**👤 {st.session_state.get('username', 'User')}**")
        role_badge = "👑 Admin" if st.session_state.get("role") == "admin" else "👁️ Viewer"
        st.markdown(f"<small>{role_badge}</small>", unsafe_allow_html=True)
    with col2:
        if st.button("🚪", help="Logout"):
            st.session_state.user_id = None
            st.session_state.username = None
            st.session_state.role = None
            st.switch_page("pages/0_Login.py")

# Main Page — hero banner
hero(
    "🤖 Multi-Agent Student Feedback Intelligence",
    "Six specialized AI agents work together — cleaning, embedding, sensing sentiment, "
    "discovering themes, guarding against bias, and recommending action — to turn raw "
    "student voices into decisions."
)

st.success(f"✅ Signed in as **{st.session_state.get('username')}** · {st.session_state.get('role')}")

# Feature cards
st.markdown("### What you can do")
c1, c2, c3 = st.columns(3)
with c1:
    st.markdown(feature_card("📤", "Upload & Analyze", "Drop a feedback CSV and deploy the agent pipeline in one click."), unsafe_allow_html=True)
with c2:
    st.markdown(feature_card("📊", "Live Dashboard", "KPIs, sentiment split, themes and keyword analytics in real time."), unsafe_allow_html=True)
with c3:
    st.markdown(feature_card("🧠", "Agent Reasoning", "See every agent's chain of thought — full transparency per feedback."), unsafe_allow_html=True)

st.markdown("<div style='height:14px'></div>", unsafe_allow_html=True)
c4, c5, c6 = st.columns(3)
with c4:
    st.markdown(feature_card("💡", "Theme Discovery", "BERTopic clusters recurring issues into clear, labeled themes."), unsafe_allow_html=True)
with c5:
    st.markdown(feature_card("⚖️", "Bias & Reliability", "Flags biased or anomalous feedback before it skews decisions."), unsafe_allow_html=True)
with c6:
    st.markdown(feature_card("✨", "Recommendations", "Prioritized, actionable steps generated by LLaMA 3 via Groq."), unsafe_allow_html=True)

